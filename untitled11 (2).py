def find_similar_products(query, top_n=5):

    query_vector = product_vectorizer.transform([query.lower()])

    similarity_scores = cosine_similarity(
        query_vector,
        product_matrix
    ).flatten()

    top_indices = similarity_scores.argsort()[::-1][:top_n]

    results = product_df.iloc[top_indices].copy()
    results['Similarity Score'] = similarity_scores[top_indices]

    return results[
        results['Similarity Score'] > 0
    ]

